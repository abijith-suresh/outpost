import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cp, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const input = new URL("../../manager/dist/", import.meta.url);
const root = new URL("../", import.meta.url);
const names = [
  "index.html",
  ...(await readdir(new URL("assets/", input))).map((name) => `assets/${name}`),
];
const files = [];
for (const name of names) {
  if (name !== "index.html" && !/^assets\/[A-Za-z0-9_-]+\.(?:js|css|woff2)$/.test(name))
    throw new Error("Unexpected production asset");
  const bytes = await readFile(new URL(name, input));
  files.push({
    path: name,
    type: name.endsWith(".html")
      ? "text/html; charset=utf-8"
      : name.endsWith(".js")
        ? "text/javascript; charset=utf-8"
        : name.endsWith(".css")
          ? "text/css; charset=utf-8"
          : "font/woff2",
    sha256: createHash("sha256").update(bytes).digest("hex"),
  });
}
const moduleSource = `// Generated by scripts/package-manager.mjs from the production Solid build.\nexport const ASSET_FILES: ReadonlyArray<{ path: string; type: string; sha256: string }> = ${JSON.stringify(files, null, 2)};\n`;
const require = createRequire(import.meta.url);
const formatted = execFileSync(
  process.execPath,
  [require.resolve("@biomejs/biome/bin/biome"), "format", "--stdin-file-path=asset-map.ts"],
  { input: moduleSource, encoding: "utf8" }
);
await writeFile(new URL("src/manager/asset-map.ts", root), formatted);
await mkdir(new URL("dist/manager/", root), { recursive: true });
await cp(input, new URL("dist/manager/", root), { recursive: true });
